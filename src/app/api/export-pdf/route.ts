import { NextRequest, NextResponse } from "next/server";

// Browserless fetch + auth/DB overhead comfortably fit under 90s.
// Default App Router limit is 10s, which is too short for PDF export.
export const maxDuration = 90;

import {
  ProjectForbiddenError,
  ProjectNotFoundError,
  getAuthedPrismaUser,
  requireProjectOwnershipOrThrow,
} from "@/lib/api-auth";
import { buildDeprecationHeaders } from "@/lib/api-version";
import {
  PREVIEW_CAPTURE_QUERY_PARAM,
  PREVIEW_CAPTURE_QUERY_VALUE,
  PREVIEW_TOKEN_QUERY_PARAM,
  signPreviewToken,
} from "@/lib/preview-token";
import { classifyIntegrationError } from "@/lib/error-classify";
import {
  DEFAULT_DAILY_EXPORT_LIMIT,
  DAILY_LIMIT_ENV_VAR,
  dailyQuotaExceededPayload,
  claimDailyQuota,
  refundDailyQuota,
  resolveDailyLimit,
} from "@/lib/api-quota";
import type { QuotaClaim } from "@/lib/api-quota";
import {
  BROWSERLESS_TIMEOUT_MS,
  E2E_BROWSERLESS_PDF_URL_ENV_VAR,
  E2E_HERMETIC_ENV_VAR,
  buildBrowserlessPdfBody,
  resolveBrowserlessPdfUrl,
  fetchBrowserlessPdfWithCircuitBreaker,
} from "@/lib/browserless";
import {
  API_ERROR_UNAUTHORIZED,
  API_ERROR_RATE_LIMIT_EXCEEDED,
  API_ERROR_PDF_AUTHENTICATION_FAILED,
  API_ERROR_PDF_GENERATION_FAILED,
  API_ERROR_EXPORT_FAILED,
  API_ERROR_INVALID_REQUEST,
} from "@/lib/api-errors";

const EXPORT_PDF_ERROR_COPY = {
  auth: {
    error: "Authentication failed",
    message: "PDF export service authentication failed. Please contact support.",
    code: API_ERROR_PDF_AUTHENTICATION_FAILED,
  },
  timeout: {
    error: "PDF export timed out",
    message: "PDF generation took too long. Please try again in a moment.",
    code: API_ERROR_PDF_GENERATION_FAILED,
  },
  network: {
    error: "Network error",
    message: "Unable to reach the PDF export service. Please check your connection and try again.",
    code: API_ERROR_EXPORT_FAILED,
  },
  unknown: {
    error: "PDF export failed",
    message: "An unexpected error occurred while generating the PDF. Please try again.",
    code: API_ERROR_EXPORT_FAILED,
  },
};

// cuid() as generated by Prisma: "c" + 24 lowercase alphanumerics (25 chars).
// Anchored so nothing that could alter the preview URL path (slashes, dots,
// query characters) is ever accepted.
const PROJECT_ID_PATTERN = /^c[a-z0-9]{24}$/;

export async function POST(req: NextRequest) {
  // Hoisted so the catch block can correlate failures with the project even
  // when the error fires before/after the request body is parsed.
  let projectId: string | undefined;
  // Issue #1132: per-request record of the atomic quota claim so failures
  // after it can refund the unit.
  let exportUserId: string | undefined;
  let exportClaim: QuotaClaim | null = null;
  try {
    // 1. Session auth. Fail closed before touching any paid quota.
    const user = await getAuthedPrismaUser();
    if (!user) {
      return NextResponse.json(
        {
          error: "Unauthorized",
          message: "You must be signed in to export a PDF",
          code: API_ERROR_UNAUTHORIZED,
        },
        { status: 401, headers: buildDeprecationHeaders() }
      );
    }

    // Issue #201: daily per-user Browserless cost guardrail. Usage lives in
    // the `DailyApiUsage` Postgres table, so it survives serverless cold
    // starts and multi-instance traffic splitting (issues #784, #1131).
    // #1132: the unit is claimed ATOMICALLY just before the render (below),
    // not gate-read up front — the old check-then-charge let a concurrent
    // burst all read the same pre-spend count and overshoot the cap. A user
    // at their cap still never reaches the paid renderer.
    const exportLimit = resolveDailyLimit(
      process.env[DAILY_LIMIT_ENV_VAR.export],
      DEFAULT_DAILY_EXPORT_LIMIT
    );
    exportUserId = user.id;

    // 2. Shape-validate projectId BEFORE it is interpolated into the
    //    preview URL handed to an external service.
    const { projectId: requestedProjectId } = await req.json();
    projectId = requestedProjectId;
    if (typeof projectId !== "string" || !PROJECT_ID_PATTERN.test(projectId)) {
      return NextResponse.json(
        {
          error: "Invalid projectId",
          message: "projectId must be a valid CUID",
          code: API_ERROR_INVALID_REQUEST,
        },
        { status: 400 }
      );
    }

    // 3. Ownership check — before spending Browserless quota.
    try {
      await requireProjectOwnershipOrThrow(projectId, user);
    } catch (e) {
      if (e instanceof ProjectNotFoundError) {
        return NextResponse.json(
          { error: "Project not found", message: "Project does not exist" },
          { status: 404 }
        );
      }
      if (e instanceof ProjectForbiddenError) {
        return NextResponse.json(
          { error: "Forbidden", message: "You do not have permission to access this project." },
          { status: 403 }
        );
      }
      throw e;
    }

    // 4. App URL: the cloud browser must be able to reach this deployment.
    //    A localhost default is only ever valid in development.
    let appUrl = process.env.NEXT_PUBLIC_APP_URL;
    if (!appUrl || appUrl.trim() === "") {
      if (process.env.NODE_ENV === "production") {
        console.error(
          JSON.stringify({
            event: "export_pdf_app_url_missing",
            projectId,
          }),
          "NEXT_PUBLIC_APP_URL must be set in production (public URL of this deployment)."
        );
        return NextResponse.json(
          {
            error: "Configuration missing",
            message:
              "PDF export is not properly configured. Please contact support.",
          },
          { status: 500 }
        );
      }
      appUrl = "http://localhost:3000";
    }

    const apiKey = process.env.BROWSERLESS_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        {
          error: "Configuration missing",
          message:
            "PDF export service is not properly configured. Please contact support.",
        },
        { status: 500 }
      );
    }

    // 5. Signed, projectId-scoped token lets the cookie-less headless browser
    //    through middleware auth for THIS project only. 15-minute TTL accommodates
    //    Browserless queueing delays that can exceed the default 5-minute TTL
    //    (issue #1036).
    const token = await signPreviewToken(projectId, 15 * 60);
    // Issue #1222: the capture path marks itself so the print CSS can keep
    // this render full-bleed (@page margin 0, matching the zero margins in
    // buildBrowserlessPdfBody) while a human printing the preview from a
    // browser gets the --print-margin safe area. The param is additive to
    // the signed token and changes nothing about preview access.
    const previewUrl = `${appUrl}/preview/${projectId}?${PREVIEW_TOKEN_QUERY_PARAM}=${encodeURIComponent(token)}&${PREVIEW_CAPTURE_QUERY_PARAM}=${PREVIEW_CAPTURE_QUERY_VALUE}`;

    // 6. Credential rides in a header (Basic auth, `apiKey:`), never the
    //    query string; bounded by an AbortController so a hung Browserless
    //    call cannot hold the request open forever.
    // Issue #201/#1132: claim one export unit ATOMICALLY here, on the
    // eve of the Browserless call. The conditional increment (UPDATE ...
    // WHERE count <= limit - N) is serialized by Postgres, so a
    // concurrent burst can no longer all read the same pre-spend count
    // and all reach the paid renderer; losers get 429 with the same
    // payload shape as before.
    exportClaim = await claimDailyQuota("export", user.id, exportLimit);
    if (!exportClaim.claimed) {
      console.warn(
        JSON.stringify({
          event: "export_pdf_daily_quota_exceeded",
          userId: user.id,
          used: exportClaim.used,
          limit: exportClaim.limit,
        })
      );
      return NextResponse.json(
        {
          ...dailyQuotaExceededPayload(exportClaim, "Please try again tomorrow."),
          code: API_ERROR_RATE_LIMIT_EXCEEDED,
        },
        { status: 429 }
      );
    }

    const controller = new AbortController();
    const timeoutId = setTimeout(
      () => controller.abort(),
      BROWSERLESS_TIMEOUT_MS
    );

    let chromeResponse: Response;
    try {
      // Issue #1084: the endpoint resolves through the hermetic-gated
      // resolver, so the hermetic e2e suite can drive this REAL route
      // handler against a local mock Browserless. A Playwright
      // `page.route` cannot do this — the fetch below is server-side, so
      // browser-context interception never sees it. Outside the e2e
      // harness (both env vars unset) this is the real endpoint.
      chromeResponse = await fetchBrowserlessPdfWithCircuitBreaker(
        resolveBrowserlessPdfUrl(
          process.env[E2E_HERMETIC_ENV_VAR],
          process.env[E2E_BROWSERLESS_PDF_URL_ENV_VAR]
        ),
        {
          method: "POST",
          headers: {
            "Content-Type": "application/json",
            Authorization: `Basic ${Buffer.from(`${apiKey}:`).toString("base64")}`,
          },
          body: JSON.stringify(buildBrowserlessPdfBody(previewUrl)),
          signal: controller.signal,
        }
      );
    } finally {
      clearTimeout(timeoutId);
    }

    if (!chromeResponse.ok) {
    // Issue #1132: the render failed, so the claimed unit is refunded
    // (Browserless errors do not count against the user's daily cap).
      if (exportUserId) {
        await refundDailyQuota("export", exportUserId);
      }
      const errorText = await chromeResponse.text();
      console.error(
        JSON.stringify({
          event: "export_pdf_browserless_error",
          projectId,
          status: chromeResponse.status,
        }),
        errorText
      );

      if (chromeResponse.status === 401 || chromeResponse.status === 403) {
        return NextResponse.json(
          {
            error: "Authentication failed",
            message: "PDF export service authentication failed. Please contact support.",
            code: API_ERROR_PDF_AUTHENTICATION_FAILED,
          },
          { status: chromeResponse.status }
        );
      }

      if (chromeResponse.status === 429) {
        return NextResponse.json(
          {
            error: "Rate limit exceeded",
            message: "PDF export service is busy. Please wait a moment and try again.",
            retryable: true,
            code: API_ERROR_RATE_LIMIT_EXCEEDED,
          },
          { status: 429 }
        );
      }

      return NextResponse.json(
        {
          error: "PDF generation failed",
          message: "Unable to generate PDF at this time. Please try again.",
          retryable: true,
          code: API_ERROR_PDF_GENERATION_FAILED,
        },
        { status: chromeResponse.status }
      );
    }

    // 7. Sanity-check the payload really is a PDF before streaming it to
    //    the user (e.g. an HTML error page slipped through with a 200).
    const pdfBuffer = await chromeResponse.arrayBuffer();
    const contentType = chromeResponse.headers.get("content-type") ?? "";
    const leadingBytes = String.fromCharCode(
      ...new Uint8Array(pdfBuffer.slice(0, 4))
    );
    if (
      pdfBuffer.byteLength === 0 ||
      !contentType.includes("application/pdf") ||
      leadingBytes !== "%PDF"
    ) {
    // Issue #1132: the render failed, so the claimed unit is refunded
    // (Browserless errors do not count against the user's daily cap).
      console.error(
        JSON.stringify({
          event: "export_pdf_non_pdf_response",
          projectId,
          contentType,
          byteLength: pdfBuffer.byteLength,
        })
      );
      return NextResponse.json(
        {
          error: "PDF generation failed",
          message: "Unable to generate PDF at this time. Please try again.",
          retryable: true,
          code: API_ERROR_PDF_GENERATION_FAILED,
        },
        { status: 502 }
      );
    }

    // No charge is written here: the unit was claimed atomically before
    // the render (issue #1132). Browserless errors and non-PDF payloads
    // refund the claim, so they do not count against the user's daily cap.

    return new NextResponse(pdfBuffer, {
      status: 200,
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": `attachment; filename="project-${projectId}.pdf"`,
      },
    });
  } catch (error) {
    // Issue #1132: give the claimed unit back when the render fails.
    if (exportUserId && exportClaim?.claimed) {
      await refundDailyQuota("export", exportUserId);
    }
    console.error(
      JSON.stringify({
        event: "export_pdf_failed",
        projectId: projectId ?? null,
      }),
      error
    );

    const classified = classifyIntegrationError(error, EXPORT_PDF_ERROR_COPY);

    return NextResponse.json(
      {
        error: classified.error,
        message: classified.message,
        retryable: classified.retryable,
        code: classified.code,
      },
      { status: classified.status }
    );
  }
}
